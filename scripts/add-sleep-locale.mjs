for (const lang of ["en", "tw", "ee", "ga"]) {
  const path = `src/locales/${lang}.json`;
  const raw = fs.readFileSync(path, "utf8");
  const parsed = JSON.parse(raw); // validate current content
  if (parsed.sleep) {
    console.log(`${lang}: sleep namespace already present, skipping`);
    continue;
  }
  // Insert before the final closing brace, preserving the rest byte-for-byte.
  const end = raw.lastIndexOf("}");
  const beforeEnd = raw.lastIndexOf("}", end - 1);
  const block = JSON.stringify(sleep[lang], null, 4)
    .split("\n")
    .map((l, i) => (i === 0 ? l : "  " + l))
    .join("\n");
  const updated =
    raw.slice(0, beforeEnd + 1) + ",\n  \"sleep\": " + block + raw.slice(beforeEnd + 1);
  JSON.parse(updated); // validate result before writing
  fs.writeFileSync(path, updated);
  console.log(`${lang}: sleep namespace added`);
}
